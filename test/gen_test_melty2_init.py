#!/usr/bin/env python3
# This script generates test_melty2_init.h

import struct

MASK64 = 0xffffffffffffffff


def rotl64(x, s):
    return (x << s | x >> (64 - s)) & MASK64


def siphash24(key, msg):
    """SipHash-2-4 with 64bit output (reference algorithm)."""
    if len(key) != 16:
        raise ValueError("key length must be 16")
    k0, k1 = struct.unpack("<2Q", key)
    v = [
        0x736f6d6570736575 ^ k0,
        0x646f72616e646f6d ^ k1,
        0x6c7967656e657261 ^ k0,
        0x7465646279746573 ^ k1,
    ]

    def sipround():
        v[0] = (v[0] + v[1]) & MASK64
        v[1] = rotl64(v[1], 13) ^ v[0]
        v[0] = rotl64(v[0], 32)
        v[2] = (v[2] + v[3]) & MASK64
        v[3] = rotl64(v[3], 16) ^ v[2]
        v[0] = (v[0] + v[3]) & MASK64
        v[3] = rotl64(v[3], 21) ^ v[0]
        v[2] = (v[2] + v[1]) & MASK64
        v[1] = rotl64(v[1], 17) ^ v[2]
        v[2] = rotl64(v[2], 32)

    tail_len = len(msg) % 8
    blocks = [struct.unpack_from("<Q", msg, i)[0] for i in range(0, len(msg) - tail_len, 8)]
    last = (len(msg) & 0xff) << 56
    for i, c in enumerate(msg[len(msg) - tail_len:]):
        last |= c << (8 * i)
    for m in blocks + [last]:
        v[3] ^= m
        sipround()
        sipround()
        v[0] ^= m
    v[2] ^= 0xff
    for _ in range(4):
        sipround()
    return v[0] ^ v[1] ^ v[2] ^ v[3]


def check_siphash24():
    # test vectors from the reference implementation (key = 00 01 .. 0f, msg = 00 01 .. (n-1))
    key = bytes(range(16))
    expected = {
        0: 0x726fdb47dd0e0e31,
        8: 0x93f5f5799a932462,
        15: 0xa129ca6149be45e5,
    }
    for n, e in expected.items():
        if siphash24(key, bytes(range(n))) != e:
            raise ValueError(f"siphash24 test vector failed for length {n}")


def derive_key(seed):
    check_seed(seed)
    sip_key = struct.pack("<4L", *seed)
    key = []
    for i in range(3):
        h = siphash24(sip_key, struct.pack("<Q", i))
        key += [h & 0xffffffff, h >> 32]
    return key


def check_seed(seed):
    if len(seed) != 4:
        raise ValueError("seed length must be 4")
    for s in seed:
        if not 0 <= s < 2 ** 32:
            raise ValueError("each seed value must be in [0, 2**32)")


def gen_tests(f):
    check_siphash24()
    cases = [
        [0, 0, 0, 0],
        [1, 2, 3, 4],
        [3141592653, 2718281828, 0x67452301, 0xefcdab89],
    ]

    def to_literal(ary):
        return "{" + ", ".join("UINT32_C(0x{:08x})".format(v) for v in ary) + "}"

    f.write("typedef struct {\n")
    f.write("    uint32_t seed[4];\n")
    f.write("    uint32_t key[6];\n")
    f.write("} TestCase;\n")
    f.write("\n")
    f.write("static const TestCase test_cases[] = {\n")
    for seed in cases:
        check_seed(seed)
        f.write(f"    {{{to_literal(seed)},\n")
        f.write(f"     {to_literal(derive_key(seed))}}},\n")
    f.write("};\n")


if __name__ == "__main__":
    with open("test_melty2_init.h", "w") as f:
        f.write("/* This file is generated by gen_test_melty2_init.py */\n")
        f.write("\n")
        gen_tests(f)

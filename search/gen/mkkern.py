# mkkern.py "structure" M > kern.h : unrolled block() computing the first M ops of the structure for
# LANES consecutive counters, which compilers vectorize. With swp, the upper and lower 32bit of the
# counter are swapped before the injection (the other counter order).
import sys

ops = [t.split() for t in sys.argv[1].split(';') if t.strip()][:int(sys.argv[2])]
body = []
d = 0
for t in ops:
    c, d, s = t[0][0], int(t[0][1:]), int(t[1])
    if c == 'A':
        body.append(f"v{d} += v{s};")
    elif c == 'X':
        body.append(f"v{d} ^= v{s};")
    else:
        r = int(t[2])
        body.append(f"v{d} ^= v{s}; v{d} = (v{d} << {r}) | (v{d} >> {32 - r});" if r else f"v{d} ^= v{s};")
ops_s = "\n            ".join(body)


def lane(cexpr):
    return f"""        for (int l = 0; l < LANES; ++l) {{
            uint64_t c = {cexpr};
            uint32_t lo = (uint32_t)c, hi = (uint32_t)(c >> 32);
            uint32_t v0 = k0 ^ lo, v1 = k1 + hi, v2 = k2 ^ hi, v3 = k3 + lo, v4 = k4, v5 = k5;
            {ops_s}
            out[l] = v{d};
        }}"""


print(f"""/* generated by mkkern.py: {len(ops)} ops */
#define LANES 64
static inline void block(const uint32_t *k, uint64_t c0, int swp, uint32_t *restrict out) {{
    const uint32_t k0 = k[0], k1 = k[1], k2 = k[2], k3 = k[3], k4 = k[4], k5 = k[5];
    (void)k4; (void)k5;
    if (!swp) {{
{lane("c0 + l")}
    }} else {{
{lane("((c0 + l) << 32) | ((c0 + l) >> 32)")}
    }}
}}""")

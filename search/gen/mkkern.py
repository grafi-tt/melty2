"""Print kern.hpp, which defines block() computing the first M ops of the structure.

block(k, c0, swp, out) computes the outputs for the LANES consecutive counters from c0 with the key k
into out. The ops are unrolled into straight-line code, which compilers vectorize over the lanes. With
swp, the upper and lower 32bit of the counter are swapped before the injection (the other counter
order). kKernM is M, and kLanes is LANES. gen/run.sh compiles the tools in gen/ with the generated
kern.hpp.
"""
import argparse

parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument("structure", help='ops separated by ";", e.g. "R1 0 5;A2 1;..."')
parser.add_argument("M", type=int, help="number of ops from the beginning")
args = parser.parse_args()

ops = [t.split() for t in args.structure.split(';') if t.strip()][:args.M]
body = []
d = 0
for t in ops:
    c, d, s = t[0][0], int(t[0][1:]), int(t[1])
    if c == 'A':
        body.append(f"v{d} += v{s};")
    elif c == 'X':
        body.append(f"v{d} ^= v{s};")
    elif c == 'S':
        body.append(f"v{d} -= v{s};")
    else:
        r = int(t[2])
        body.append(f"v{d} ^= v{s}; v{d} = (v{d} << {r}) | (v{d} >> {32 - r});" if r else f"v{d} ^= v{s};")
ops_s = "\n            ".join(body)


def lane(cexpr):
    """Return the C++ loop over the lanes, computing the output for the counter cexpr of the lane l."""
    return f"""        for (int l = 0; l < kLanes; ++l) {{
            const uint64_t c = {cexpr};
            const uint32_t lo = static_cast<uint32_t>(c), hi = static_cast<uint32_t>(c >> 32);
            [[maybe_unused]] uint32_t v0 = k0 ^ lo, v1 = k1 + hi, v2 = k2 ^ hi, v3 = k3 + lo, v4 = k4, v5 = k5;
            {ops_s}
            out[l] = v{d};
        }}"""


print(f"""// generated by mkkern.py: {len(ops)} ops
#include <cstdint>

inline constexpr int kKernM = {len(ops)};
inline constexpr int kLanes = 64;

inline void block(const uint32_t *k, uint64_t c0, int swp, uint32_t *__restrict out) {{
    const uint32_t k0 = k[0], k1 = k[1], k2 = k[2], k3 = k[3];
    [[maybe_unused]] const uint32_t k4 = k[4], k5 = k[5];
    if (!swp) {{
{lane("c0 + static_cast<uint64_t>(l)")}
    }} else {{
{lane("((c0 + l) << 32) | ((c0 + l) >> 32)")}
    }}
}}""")
